// todo arquivo que contém código fonte em java
// tem a extensão .java e seu bytecode corresponde
// ao arquivo com a extensão .class

// todo programar em java está dentro de uma classe
// abaixo o programar está na classe Main
// é importante que o nome da classe seja o mesmo nome
// do arquivo com a extensão .java, nesse caso
// arquivo: Main.java Classe: Main
// atencao, java é uma linguagem case sensitive, ou seja
// diferencia letras maiuscula de minuiscula e vise-versa
public class Main{
    // abaixo é o metodo main, o metodo principal da classe
    public static void main(String[]args){
        // abaixo é o comando que exibira uma mensagem no terminal
        // atencao, a maioria dos comandos em java terminar com ponto e virgula
        System.out.print("ola mundo");
        // abaixo, tambem exibira uma mensagem no terminal
        // no entanto, com a adicao de ln, que fara com que pule uma linha
        System.out.println(" ola novamente");
    }
}